// Builds upload/worker.js: embeds everything in public/ into the Worker and bundles it into one file.
// Usage: npm install (first time only), then: npm run build
import fs from 'node:fs';import path from 'node:path';import crypto from 'node:crypto';import {execSync} from 'node:child_process';
const ROOT=path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1'));
const PUB=path.join(ROOT,'public');
const TYPES={'.html':'text/html; charset=utf-8','.css':'text/css; charset=utf-8','.js':'text/javascript; charset=utf-8','.png':'image/png','.jpg':'image/jpeg','.jpeg':'image/jpeg','.webp':'image/webp','.svg':'image/svg+xml','.ico':'image/x-icon','.webmanifest':'application/manifest+json','.json':'application/json','.txt':'text/plain; charset=utf-8','.woff2':'font/woff2'};
const walk=d=>fs.readdirSync(d,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(d,e.name)):[path.join(d,e.name)]);
const files=walk(PUB).filter(f=>TYPES[path.extname(f).toLowerCase()]).sort();
// a version stamp from the file contents, so phones and browsers fetch the new graphics/code instead of old cached copies
const h=crypto.createHash('sha256');for(const f of files)h.update(f).update(fs.readFileSync(f));const ver=h.digest('hex').slice(0,8);
const out={};
for(const f of files){
  const rel='/'+path.relative(PUB,f).split(path.sep).join('/'),t=TYPES[path.extname(f).toLowerCase()];
  if(/^(text|application)\//.test(t)){let s=fs.readFileSync(f,'utf8');
    if(rel.endsWith('.html'))s=s.replace(/(\.(?:css|js)\?v=)[\w.-]+/g,'$1'+ver);
    if(rel==='/sw.js')s=s.replace(/const V='omi-[\w.-]+'/,`const V='omi-${ver}'`).replace(/\?v=[\w.-]+/g,'?v='+ver);
    out[rel]={t,s};}
  else out[rel]={t,b:fs.readFileSync(f).toString('base64')};
}
fs.writeFileSync(path.join(ROOT,'src','assets.js'),'// Generated by build.mjs – do not edit. Edit files in public/ instead.\nexport const FILES='+JSON.stringify(out)+';\n');
console.log(`Embedded ${files.length} files from public/ (version ${ver})`);
const tmp=path.join(ROOT,'.build');fs.rmSync(tmp,{recursive:true,force:true});
execSync(`npx wrangler deploy --dry-run --config wrangler.build.jsonc --outdir "${tmp}"`,{cwd:ROOT,stdio:'inherit'});
const UP=path.join(ROOT,'upload');fs.mkdirSync(UP,{recursive:true});
fs.writeFileSync(path.join(UP,'worker.js'),'// OMI LANKA – complete game server + website in one file. Generated by build.mjs; edit the source project instead.\n'+fs.readFileSync(path.join(tmp,'worker.js'),'utf8'));
fs.copyFileSync(path.join(ROOT,'deploy','wrangler.jsonc'),path.join(UP,'wrangler.jsonc'));
fs.copyFileSync(path.join(ROOT,'deploy','package.json'),path.join(UP,'package.json'));
fs.rmSync(tmp,{recursive:true,force:true});
const kb=Math.round(fs.statSync(path.join(UP,'worker.js')).size/1024);
console.log(`\n✅ Done. Upload the 3 files in the "upload" folder to GitHub (worker.js is ${kb} KB).`);
